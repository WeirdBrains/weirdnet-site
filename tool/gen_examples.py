#!/usr/bin/env python3
"""Generate lib/content/examples.dart from tool/examples/*.rs and examples.toml.

With --harness DIR it also writes one Cargo package per example (each its own workspace, as
a separate app would be, depending on the published crates exactly as the page shows) and
check.sh, which builds every package and runs the ones that can run offline:

    python3 tool/gen_examples.py --harness /tmp/weirdnet-examples
    CARGO_TARGET_DIR=/tmp/weirdnet-examples-target /tmp/weirdnet-examples/check.sh

Run the harness outside the site checkout and clear its target directory afterwards.
"""
import argparse, pathlib, tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EX = ROOT / "tool" / "examples"


def toml_value(v):
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {toml_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(v)


def deps_block(deps):
    return "[dependencies]\n" + "\n".join(f"{k} = {toml_value(v)}" for k, v in deps.items())


def dart_string(s):
    return "r'''" + s + "'''" if "'''" not in s else repr(s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--harness")
    a = ap.parse_args()
    meta = tomllib.loads((EX / "examples.toml").read_text())
    out = [
        "// Generated by tool/gen_examples.py from tool/examples/. Do not edit by hand.",
        "library;",
        "",
        "/// A crate page example: the [dependencies] it needs and the program.",
        "class Example {",
        "  const Example(this.deps, this.code);",
        "  final String deps;",
        "  final String code;",
        "}",
        "",
        "const examples = <String, Example>{",
    ]
    for slug, m in meta.items():
        code = (EX / f"{slug}.rs").read_text().rstrip() + "\n"
        out.append(f"  '{slug}': Example(\n    {dart_string(deps_block(m['deps']))},\n    {dart_string(code)},\n  ),")
    out.append("};")
    (ROOT / "lib" / "content" / "examples.dart").write_text("\n".join(out) + "\n")

    if a.harness:
        h = pathlib.Path(a.harness)
        h.mkdir(parents=True, exist_ok=True)
        members, runs = [], []
        for slug, m in meta.items():
            d = h / f"ex-{slug}"
            d.mkdir(exist_ok=True)
            members.append(f'"ex-{slug}"')
            src = (EX / f"{slug}.rs").resolve()
            if m.get("lib"):
                target = f'[lib]\npath = "{src}"\ncrate-type = ["cdylib"]\n'
            else:
                target = f'[[bin]]\nname = "ex-{slug}"\npath = "{src}"\n'
                if m.get("run", True):
                    runs.append(f"ex-{slug}")
            (d / "Cargo.toml").write_text(
                f'[package]\nname = "ex-{slug}"\nversion = "0.0.0"\nedition = "2024"\npublish = false\n\n[workspace]\n\n{target}\n{deps_block(m["deps"])}\n'
            )
        script = ["#!/bin/sh", "# Build every example; run the offline ones. Prints FAIL lines.", 'cd "$(dirname "$0")"', "fails=0"]
        for mem in members:
            name = mem.strip('"')
            script.append(f'echo "== {name}"; (cd {name} && cargo build -q) || {{ echo "FAIL build {name}"; fails=$((fails+1)); }}')
        for r in runs:
            script.append(f'(cd {r} && cargo run -q) >/dev/null || {{ echo "FAIL run {r}"; fails=$((fails+1)); }}')
        script.append('echo "failures: $fails"; [ "$fails" = 0 ]')
        (h / "check.sh").write_text("\n".join(script) + "\n")
        (h / "check.sh").chmod(0o755)


if __name__ == "__main__":
    main()
